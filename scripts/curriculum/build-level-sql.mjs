#!/usr/bin/env node
// Generates a Supabase migration SQL file for one Level of a course's
// curriculum, given a plain JSON lesson plan. This is the reusable,
// course-agnostic half of the curriculum pipeline: it does not know or
// care whether it's building Cybersecurity, Blender, or anything else —
// it just turns { level, modules: [{ lessons: [...] }] } into correctly
// escaped SQL.
//
// It exists because hand-typing SQL string literals for 15-30 lessons per
// level is error-prone (quote escaping, JSON-in-SQL). The actual
// curriculum content (what the levels/modules/lessons should be, and
// which real YouTube video matches each lesson) is still designed and
// researched separately — see README's "Curriculum generation, without
// the paid API" section for that process. This script is only the last,
// mechanical step: plan -> safe SQL.
//
// Usage:
//   node scripts/curriculum/build-level-sql.mjs <plan.json> <out.sql>
//
// Plan JSON shape:
// {
//   "courseId": "uuid",
//   "level": { "title": "...", "description": "...", "orderNumber": 2 },
//   // ...or, to APPEND modules to a level that already exists (the
//   // breadth-first deepening case), name it instead of describing it:
//   "level": { "orderNumber": 1, "existing": true },
//   "modules": [
//     {
//       "title": "...", "description": "...",
//       "lessons": [
//         {
//           "title": "...", "description": "...", "youtubeId": "...",
//           "objectives": ["...", "..."],
//           "notes": "...",
//           "practice": "...",
//           "quiz": [{ "question": "...", "options": ["...", ...], "correct_index": 0 }]
//         }
//       ]
//     }
//   ]
// }
import { readFileSync, writeFileSync } from "fs";

const [, , planPath, outPath] = process.argv;
if (!planPath || !outPath) {
  console.error("Usage: node build-level-sql.mjs <plan.json> <out.sql>");
  process.exit(1);
}

const plan = JSON.parse(readFileSync(planPath, "utf8"));

function sqlStr(s) {
  return "'" + String(s).replace(/'/g, "''") + "'";
}
function sqlArray(arr) {
  return "array[" + arr.map(sqlStr).join(", ") + "]";
}
function sqlQuiz(quiz) {
  return `'${JSON.stringify(quiz).replace(/'/g, "''")}'::jsonb`;
}

function lessonRow(varName, lesson, orderNumber) {
  return `    (${varName}, ${sqlStr(lesson.title)}, ${sqlStr(lesson.description)}, 'https://www.youtube.com/watch?v=${lesson.youtubeId}', ${orderNumber},
      ${sqlArray(lesson.objectives)},
      ${sqlStr(lesson.notes)},
      ${sqlStr(lesson.practice)},
      ${sqlQuiz(lesson.quiz)})`;
}

const moduleVarNames = plan.modules.map((_, i) => `v_m${i + 1}`);

let sql = `-- Auto-generated by scripts/curriculum/build-level-sql.mjs -- do not
-- hand-edit the lesson content below; regenerate from the source plan
-- JSON instead if something needs to change.

do $$
declare
  v_course_id uuid := '${plan.courseId}';
  v_level uuid;
  -- modules.order_number is unique per COURSE, not per level (a course's
  -- modules are numbered continuously across all its levels) -- so this
  -- can't just start at 1 for a level beyond the first. Computed here
  -- instead of hardcoded so this script works correctly regardless of how
  -- many modules the course already has.
  v_module_offset int;
  ${moduleVarNames.map((v) => `${v} uuid;`).join("\n  ")}
begin
${
  plan.level.existing
    ? `  -- Appending to a level that already exists. Looked up rather than
  -- inserted, so this adds to the learner's current Level ${plan.level.orderNumber} instead of
  -- creating a duplicate one, and no existing module is re-parented.
  select id into v_level from public.levels
    where course_id = v_course_id and order_number = ${plan.level.orderNumber};

  if v_level is null then
    raise exception 'Level % not found for course % -- refusing to guess', ${plan.level.orderNumber}, v_course_id;
  end if;

  -- The new modules must sit INSIDE this level, not at the end of the
  -- course. getOrderedLessons() builds the learner's lesson sequence from
  -- modules.order_number alone and ignores level, so a module appended at
  -- the course's max order would put beginner content after the final
  -- level's material. Insert straight after this level's last module and
  -- shift everything below it down instead.
  select coalesce(max(order_number), 0) into v_module_offset
    from public.modules where level_id = v_level;

  -- Two-phase shift: (course_id, order_number) is unique, and a single
  -- "+ N" update can trip that constraint mid-statement, so park the rows
  -- out of range first and bring them back afterwards.
  update public.modules set order_number = order_number + 1000
   where course_id = v_course_id and order_number > v_module_offset;
`
    : `  select coalesce(max(order_number), 0) into v_module_offset
    from public.modules where course_id = v_course_id;

  insert into public.levels (course_id, title, description, order_number) values
    (v_course_id, ${sqlStr(plan.level.title)}, ${sqlStr(plan.level.description)}, ${plan.level.orderNumber})
  returning id into v_level;
`
}
`;

plan.modules.forEach((mod, i) => {
  sql += `  insert into public.modules (course_id, level_id, title, description, order_number) values
    (v_course_id, v_level, ${sqlStr(mod.title)}, ${sqlStr(mod.description)}, v_module_offset + ${i + 1})
  returning id into ${moduleVarNames[i]};

  insert into public.lessons (module_id, title, description, youtube_url, order_number, learning_objectives, notes, practice_activity, knowledge_check) values
${mod.lessons.map((l, li) => lessonRow(moduleVarNames[i], l, li + 1)).join(",\n")}
  on conflict (module_id, order_number) do nothing;

`;
});

if (plan.level.existing) {
  sql += `  -- Bring the shifted modules back, now sitting after the ${plan.modules.length} new one(s).
  update public.modules set order_number = order_number - 1000 + ${plan.modules.length}
   where course_id = v_course_id and order_number > 1000;

`;
}

sql += `end $$;\n`;

writeFileSync(outPath, sql);

const totalModules = plan.modules.length;
const totalLessons = plan.modules.reduce((sum, m) => sum + m.lessons.length, 0);
console.log(`Wrote ${outPath}`);
console.log(
  plan.level.existing
    ? `Level: appending to existing level ${plan.level.orderNumber}`
    : `Level: ${plan.level.title}`
);
console.log(`Modules: ${totalModules}`);
console.log(`Lessons: ${totalLessons}`);
