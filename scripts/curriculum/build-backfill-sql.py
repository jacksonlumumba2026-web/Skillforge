#!/usr/bin/env python3
"""Turn a backfill plan (existing lesson ids + written content) into UPDATE SQL.

Backfilling differs from build-level-sql.mjs: it adds notes, objectives,
practice and knowledge_check to lessons that ALREADY EXIST, addressed by id.
Nothing is inserted, deleted or re-parented, and no lesson id changes, so
learner progress is untouched.

Usage: python3 scripts/curriculum/build-backfill-sql.py <plan.json> <out.sql>
"""
import json, sys

def q(s):
    return "'" + str(s).replace("'", "''") + "'"

def arr(xs):
    return "array[" + ", ".join(q(x) for x in xs) + "]"

def quiz(z):
    return q(json.dumps(z, ensure_ascii=False)) + "::jsonb"

plan = json.load(open(sys.argv[1]))
out = [
    "-- Auto-generated by scripts/curriculum/build-backfill-sql.py -- do not",
    "-- hand-edit; regenerate from the source plan JSON instead.",
    "--",
    "-- UPDATE only, addressed by lesson id. No lesson is inserted, deleted or",
    "-- re-parented and no id changes, so lesson_progress is untouched.",
    "",
]
for l in plan["lessons"]:
    out.append(f"-- {l['title']}")
    out.append("update public.lessons set")
    out.append(f"  learning_objectives = {arr(l['objectives'])},")
    out.append(f"  notes = {q(l['notes'])},")
    out.append(f"  practice_activity = {q(l['practice'])},")
    out.append(f"  knowledge_check = {quiz(l['quiz'])}")
    out.append(f"where id = '{l['id']}';")
    out.append("")

open(sys.argv[2], "w").write("\n".join(out))
print(f"Wrote {sys.argv[2]} -- {len(plan['lessons'])} lessons backfilled")
